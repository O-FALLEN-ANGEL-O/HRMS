/**
 * Bundles drizzle/migrations/*.sql into src/db/migrations.gen.ts so the Worker
 * can apply them itself on first run (see src/db/setup.ts). Runs after
 * `npm run db:generate`; the output is committed.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const dir = "drizzle/migrations";
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();
const migrations = files.map((name) => ({
  name,
  statements: readFileSync(`${dir}/${name}`, "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}));

writeFileSync(
  "src/db/migrations.gen.ts",
  `// Generated by scripts/bundle-migrations.ts from ${dir}. Do not edit.\nexport const MIGRATIONS: { name: string; statements: string[] }[] = ${JSON.stringify(migrations, null, 2)};\n`,
);
console.log(`Bundled ${migrations.length} migration(s) into src/db/migrations.gen.ts`);
